# 添加数据

class BookBase(BaseModel):
    id: int
    author: str
    price: float
    bookname:str
    publisher: str

@app.post("/book/add_book")
async def add_book(book: BookBase, db: AsyncSession = Depends(get_database)):
    # 获取 book 参数，创建图书对象（__dict__ 返回 book 对象的属性字典）
    book_obj = Book(**book.__dict__)
    db.add(book_obj)
    await db.commit()
    return book



