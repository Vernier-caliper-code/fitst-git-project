""""
ORM（Object-RelationalMapping，对象关系映射）是一种编程技术，用于在面向对象编程语言和关系型数据库之间建立映射。它允许开发者通过操作对象的方式与数据库进行交互，而无需直接编写复杂的SQL语句。

优势:
减少重复的SQL 代码
代码更简洁易读
自动处理数据库连接和事务
自动防止SQL注入攻击

1. 安装SQLAlchemy
sqlalchemy[asyncio]、aiomysql(异步数据库驱
动)

2. 创建数据库连接
数据库连接地址：数据库类型+驱动://用户名:密码@主机:端口/数据库名?参数

"""


from datetime import datetime

from fastapi import Depends, FastAPI, HTTPException
from pydantic import BaseModel
from sqlalchemy import DateTime, Float, String, func, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

app=FastAPI()

ASYNC_DATABASE_URL = "mysql+aiomysql://root:123456@localhost:3306/FastAPI_first?charset=utf8"

#1.创建异步引擎
async_engine=create_async_engine(
    ASYNC_DATABASE_URL,
    echo=True,  #  可选，，输出 SQL 语句
    pool_size=10,  #  可选，设置连接池活跃的连接数
    max_overflow=20  #  允许额外的连接数
)

# 2. 定义模型类： 基类 + 表对应的模型类
# 基类：创建时间、更新时间；书籍表：id、书名、作者、价格、出版社

# 这里的DeclarativeBase 是为了提供ORM声明式映射能力
class Base(DeclarativeBase):
    create_time: Mapped[datetime] = mapped_column(DateTime, insert_default=func.now(), default=func.now, comment="创建时间")
    update_time: Mapped[datetime] = mapped_column(DateTime, insert_default=func.now(), default=func.now, onupdate=func.now(),comment="更新时间")


class Book(Base):
    __tablename__ = "book"

    id: Mapped[int] = mapped_column(primary_key=True, comment="书籍id")
    bookname: Mapped[str] = mapped_column(String(255), comment="书名")
    author: Mapped[str] = mapped_column(String(255), comment="作者")
    price: Mapped[float] = mapped_column(Float, comment="价格")
    publisher: Mapped[str] = mapped_column(String(255), comment="出版社")


# 3. 建表：定义函数建表 -> FastAPI 启动的时候调用建表的函数

async def create_tables():
    # 获取异步引擎，创建事务 - 建表
    async with async_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)  # Base.metadata 是一个共享的元数据容器。所有继承 Base 并设置了 __tablename__ 的模型，都会把自己的表结构注册进去。




@app.on_event("startup")
async def startup_event():
    await create_tables()




@app.get("/")
async def root():
    return {"message": "Hello World"}   





# 需求：查询功能的接口，查询图书 -> 依赖注入：创建依赖项获取数据库会话 + Depends 注入路由处理函数
AsyncSessionLocal = async_sessionmaker(
    bind=async_engine,  # 绑定数据库引擎
    class_=AsyncSession,  # 指定会话类
    expire_on_commit=False  # 提交后会话不过期，不会重新查询数据库
)


# 依赖项
async def get_database():
    async with AsyncSessionLocal() as session:
        try:
            yield session  # 返回数据库会话给路由处理函数
            await session.commit()  # 提交事务
        except Exception:
            await session.rollback()  # 有异常，回滚
            raise


@app.get('/book/books')
async def get_books(db: AsyncSession = Depends(get_database)):
    results=await db.execute(select(Book))   #得到orm对象
    books=results.scalars().all()
    return books
 
# scalars().first()   获取单挑数据
# get(模型类，主键值)  获取单条数据，根据主键  books=db.get(Book,5)  return books


