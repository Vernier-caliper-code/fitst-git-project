#一、条件查询   select(模型类).where(条件)
#1.比较查询
@app.get('/book/books/{id}')
async def get_book(id: int, db: AsyncSession = Depends(get_database)):
    result=await db.execute(select(Book).where(Book.id==id))
    book=result.scalar_one_or_none()
    return book




#2. 模糊、包含、与非查询
@app.get('/book/books/search_book')
async def search_book(db: AsyncSession = Depends(get_database)):
    #模糊查询：   like()  %: 表示任意字符， _ :表示任意单个字符      
    #   result=await db.execute(select(Book).where(Book.author.like('曹%')))
    
    # 与非：----->: & 和  |  当有多个条件用
    # result=await db.execute(select(Book).where((Book.author.like('曹%')) | (Book.price>10)) )
    
    #包含：  in_()    
    result=await db.execute(select(Book).where(Book.id.in_([1,2,3])) )
    book=result.scalars().all()
    return book


#--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 二、聚合查询 func.方法(模型名.属性)  count()  sum()  max()  min()  avg()
@app.get('/book/books/func')
async def func(db: AsyncSession = Depends(get_database)):
    result=await db.execute(select(func.count(Book.id)) )
    book=result.scalar()
    return book


#-------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------


# 三、分页查询  select(模型名).offset().limit()     说明： offset() 跳过的记录数（页数-1）*每页的记录数       limit() 返回的记录数
@app.get('/book/books/page')
async def page(
    db: AsyncSession = Depends(get_database),
    page:int=1, #查询第几页
    page_size:int=3  # 每页的记录数
):
    results=await db.execute(select(Book).offset((page-1)*page_size).limit(page_size) )
    book=results.scalars().all()
    return book


